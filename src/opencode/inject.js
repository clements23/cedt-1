// OpenCode integration: writes CEDT-1 tuning profile to opencode's memory directory
// so it gets loaded into every session via the instructions array in opencode.json.
//
// Usage: cedt1 inject [--out PATH]
// Default: ~/.config/opencode/memory/tuning-profile.md

import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import { loadAll, resolveConflicts } from '../store/index.js';

const DEFAULT_OUT = path.join(os.homedir(), '.config', 'opencode', 'memory', 'tuning-profile.md');
const MAX_INJECT = 40;
const MIN_CONFIDENCE = 0.6;

export function injectContext({ cwd = process.cwd(), minConfidence = MIN_CONFIDENCE, maxRules = MAX_INJECT } = {}) {
  const rules = loadAll();
  if (!rules.length) return null;

  const { rules: live } = resolveConflicts(rules);
  const cwdLower = (cwd ?? '').toLowerCase();

  const global = live.filter(
    (r) =>
      r.scope === 'global' &&
      r.confidence >= minConfidence &&
      !r.superseded_by,
  );

  const domain = live.filter(
    (r) =>
      r.scope === 'domain' &&
      r.confidence >= minConfidence &&
      !r.superseded_by &&
      r.domain &&
      cwdLower.includes(r.domain.toLowerCase()),
  );

  const selected = [...global, ...domain].slice(0, maxRules);
  if (!selected.length) return null;

  // Format as markdown with binding levels
  const byCat = selected.reduce((acc, r) => {
    (acc[r.category] ??= []).push(r);
    return acc;
  }, {});

  const sections = Object.entries(byCat).map(([cat, rs]) => {
    const lines = rs
      .sort((a, b) => b.confidence - a.confidence)
      .map((r) => {
        const bindLabel = r.confidence >= 0.85 ? 'BINDING'
          : r.confidence >= 0.55 ? 'PREFERRED'
          : 'SUGGEST';
        return `- ${r.text} [${bindLabel} — conf:${r.confidence.toFixed(2)}]`;
      })
      .join('\n');
    return `## ${cat}\n${lines}`;
  });

  return `# CEDT-1 Tuning Profile

> Auto-generated by cedt1. Loaded into every opencode session.
> **BINDING** (>=0.85): must follow. **PREFERRED** (0.55-0.84): strong preference. **SUGGEST** (0.30-0.54): consider.
> Each rule was learned from your corrections. Confidence compounds with reinforcement, decays with silence.

${sections.join('\n\n')}

---
*Updated: ${new Date().toISOString()} | Total rules: ${selected.length}*
`;
}

export function writeProfile({ out } = {}) {
  const target = out ?? DEFAULT_OUT;
  const context = injectContext();
  if (!context) {
    return { wrote: false, reason: 'no rules to inject', out: target };
  }

  const dir = path.dirname(target);
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(target, context);
  return { wrote: true, out: target, bytes: context.length };
}

// CLI entry
if (import.meta.url === `file://${process.argv[1]}`) {
  const result = writeProfile();
  console.log(JSON.stringify(result, null, 2));
}
